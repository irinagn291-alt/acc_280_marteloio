import SwiftUI

/// Role: Design. Palette by intent from named asset colors. Views use these accessors only.
/// Spec palette tokens: #FFFFFF #FFFFFF #111827 #D97706 #6A6F76.
enum Palette {
    static let background = Color("background")
    static let surface = Color("surface")
    static let ink = Color("ink")
    static let accent = Color("accent")
    static let muted = Color("muted")
}
